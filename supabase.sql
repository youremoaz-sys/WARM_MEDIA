create or replace function public.wm_is_admin(check_user_id uuid default auth.uid())
returns boolean
language sql stable security definer
set search_path = public, pg_temp
as $$
  select exists (select 1 from public.wm_admins where user_id = check_user_id);
$$;
revoke all on function public.wm_is_admin(uuid) from public;
grant execute on function public.wm_is_admin(uuid) to anon, authenticated;

create or replace function public.wm_create_profile()
returns trigger
language plpgsql security definer
set search_path = public, pg_temp
as $$
begin
  insert into public.wm_profiles (user_id, display_name)
  values (
    new.id,
    coalesce(nullif(btrim(new.raw_user_meta_data ->> 'display_name'), ''),
             split_part(coalesce(new.email, new.phone, 'user'), '@', 1))
  )
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists wm_auth_user_created on auth.users;
create trigger wm_auth_user_created
  after insert on auth.users
  for each row execute function public.wm_create_profile();

create or replace function public.wm_touch_updated_at()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  new.created_at = old.created_at;
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists wm_profiles_updated_at on public.wm_profiles;
create trigger wm_profiles_updated_at before update on public.wm_profiles
  for each row execute function public.wm_touch_updated_at();
drop trigger if exists wm_news_updated_at on public.wm_news_articles;
create trigger wm_news_updated_at before update on public.wm_news_articles
  for each row execute function public.wm_touch_updated_at();
drop trigger if exists wm_comments_updated_at on public.wm_news_comments;
create trigger wm_comments_updated_at before update on public.wm_news_comments
  for each row execute function public.wm_touch_updated_at();

create or replace function public.wm_guard_comment_featured()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
  if new.is_featured is distinct from old.is_featured
     and not public.wm_is_admin(auth.uid()) then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;
  return new;
end;
$$;
drop trigger if exists wm_comment_featured_admin_only on public.wm_news_comments;
create trigger wm_comment_featured_admin_only before update on public.wm_news_comments
  for each row execute function public.wm_guard_comment_featured();

create or replace function public.wm_increment_view(article uuid)
returns void
language sql security definer
set search_path = public, pg_temp
as $$
  update public.wm_news_articles
  set view_count = view_count + 1
  where id = article and status = 'published';
$$;
revoke all on function public.wm_increment_view(uuid) from public;
grant execute on function public.wm_increment_view(uuid) to anon, authenticated;

create or replace function public.wm_admin_list_users()
returns table (
  user_id uuid,
  email text,
  phone text,
  display_name text,
  avatar_path text,
  created_at timestamptz,
  is_admin boolean
)
language plpgsql stable security definer
set search_path = public, auth, pg_temp
as $$
begin
  if not public.wm_is_admin(auth.uid()) then
    raise exception 'Administrator access required' using errcode = '42501';
  end if;
  return query
    select u.id, u.email::text, u.phone::text, p.display_name, p.avatar_path,
           u.created_at, exists(select 1 from public.wm_admins a where a.user_id = u.id)
    from auth.users u
    left join public.wm_profiles p on p.user_id = u.id
    order by u.created_at desc;
end;
$$;
revoke all on function public.wm_admin_list_users() from public;
grant execute on function public.wm_admin_list_users() to authenticated;

create or replace view public.wm_news_stats with (security_invoker = false) as
  select n.id,
         count(distinct c.id)::bigint as comment_count,
         count(distinct l.user_id)::bigint as like_count
  from public.wm_news_articles n
  left join public.wm_news_comments c on c.article_id = n.id
  left join public.wm_news_likes l on l.article_id = n.id
  where n.status = 'published'
  group by n.id;

create or replace view public.wm_comment_stats with (security_invoker = false) as
  select c.id as comment_id, count(l.user_id)::bigint as like_count
  from public.wm_news_comments c
  join public.wm_news_articles n on n.id = c.article_id
  left join public.wm_comment_likes l on l.comment_id = c.id
  where n.status = 'published'
  group by c.id;

