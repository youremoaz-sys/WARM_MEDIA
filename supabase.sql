set display_name = coalesce(
  nullif(a.display_name, ''),
  (select p.display_name from public.wm_profiles p where p.user_id = a.user_id),
  (select split_part(coalesce(u.email, u.phone, 'Admin'), '@', 1)
   from auth.users u where u.id = a.user_id),
  'Admin'
);
