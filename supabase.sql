create table if not exists public.wm_news_articles (
  id uuid primary key default gen_random_uuid(),
  title text not null check (char_length(title) between 1 and 240),
  body text not null default '',
  category_id integer not null references public.wm_categories(id) on delete restrict,
  author_id uuid references auth.users(id) on delete set null,
  author_name text not null default '',
  source text not null default '',
  image_path text,
  extra_images text[] not null default '{}',
  video_paths text[] not null default '{}',
  is_breaking boolean not null default false,
  status text not null default 'published' check (status in ('draft', 'published')),
  view_count bigint not null default 0 check (view_count >= 0),
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists wm_news_published_idx
  on public.wm_news_articles (published_at desc) where status = 'published';
create index if not exists wm_news_category_idx
  on public.wm_news_articles (category_id, published_at desc);
create index if not exists wm_news_search_idx
  on public.wm_news_articles using gin
  (to_tsvector('simple', coalesce(title, '') || ' ' || coalesce(body, '') || ' ' || coalesce(source, '')));

create table if not exists public.wm_news_comments (
